export const NATIONALITIES: readonly string[] = ["Indian", ...OTHER_NATIONALITIES];

/**
 * Options for a nationality picker. A value already saved on a record that is not in the list (older free text such as
 * "Indian national") is added so editing the record never silently drops it.
 */
export function nationalityOptions(current?: string | null): { value: string; label: string }[] {
  const list = [...NATIONALITIES];
  const saved = current?.trim();
  if (saved && !list.some((n) => n.toLowerCase() === saved.toLowerCase())) list.push(saved);
  return list.map((n) => ({ value: n, label: n }));
}
