#!/usr/bin/env node
/**
 * Builds database/bundle.sql: every migration, in order, in ONE transaction, plus the same bookkeeping rows that
 * scripts/migrate.mjs writes (so `npm run db:migrate` afterwards sees everything as applied).
 *
 *   npm run db:bundle
 *
 * Paste the file into the Supabase SQL Editor (Dashboard -> SQL Editor -> New query) and run it once on a database
 * that has none of the migrations. If anything fails, nothing is applied (single transaction) and the editor shows
 * the error. Safe to re-run only on an empty schema; for an existing database use `npm run db:migrate`.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "database/migrations");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const normalise = (s) => s.replace(/\r\n/g, "\n");
const checksum = (s) => createHash("sha256").update(normalise(s)).digest("hex");

let out = `-- Smart Travel CRM: all migrations (${files.length} files) in one transaction.
-- Generated by scripts/bundle-sql.mjs. Run once on an EMPTY database.
begin;

create table if not exists public.schema_migrations (
  filename text primary key, checksum text not null, applied_at timestamptz not null default now());
alter table public.schema_migrations enable row level security;
`;
const rows = [];
for (const f of files) {
  const sql = normalise(readFileSync(path.join(dir, f), "utf8"));
  out += `\n-- ===== ${f} =====\n${sql.trimEnd()}\n`;
  rows.push(`  ('${f}', '${checksum(sql)}')`);
}
out += `\ninsert into public.schema_migrations (filename, checksum) values\n${rows.join(",\n")};\n\ncommit;\n`;

const target = path.join(root, "database/bundle.sql");
writeFileSync(target, out);
console.log(
  `Wrote ${path.relative(root, target)} (${(out.length / 1024).toFixed(0)} KB, ${files.length} migrations).`,
);
